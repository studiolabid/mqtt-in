/**
 * Shell words for the "Copy as command" generator (`@/utils/cli-command`, pure, no Vue):
 * quoting for POSIX shells and PowerShell, the password environment variable, a small command
 * line builder and the connection flags both tools share.
 *
 * Quoting: POSIX single quotes (`'` → `'\''`); PowerShell single quotes (`'` and the typographic
 * single quotes doubled). Newlines stay inside the quotes.
 */
import type { ConnectionProfile, MqttProtocolVersion } from '@shared/models'
import { isGeneratedClientId, isTlsProtocol, isWebSocketProtocol } from '@shared/defaults'

export type CliShell = 'posix' | 'powershell'

/** The environment variable the commands read the password from. */
export const PASSWORD_VARIABLE = 'MQTT_PASSWORD'

/** Arguments that need no quotes in either shell. */
const SAFE_ARGUMENT = /^[A-Za-z0-9_./:-]+$/
/** PowerShell treats the typographic single quotes as quotes too. */
const POWERSHELL_QUOTES = /['‘’‚‛]/g

/** One shell word: as is when safe, else single-quoted for the shell. */
export function quoteArgument(value: string, shell: CliShell): string {
  if (value !== '' && SAFE_ARGUMENT.test(value) && !value.startsWith('-')) return value
  if (shell === 'powershell') return `'${value.replace(POWERSHELL_QUOTES, (q) => q + q)}'`
  return `'${value.replaceAll("'", "'\\''")}'`
}

/** The password as an environment variable reference (never the password itself). */
export function passwordArgument(shell: CliShell): string {
  return shell === 'powershell' ? `$env:${PASSWORD_VARIABLE}` : `"$${PASSWORD_VARIABLE}"`
}

/** A command under construction: literal flags and values to quote. */
export class CommandLine {
  private readonly words: string[]

  constructor(
    tool: string,
    readonly shell: CliShell
  ) {
    this.words = [tool]
  }

  flag(...flags: string[]): this {
    this.words.push(...flags)
    return this
  }

  /** `flag value…` with the values quoted. */
  option(flag: string, ...values: string[]): this {
    this.words.push(flag, ...values.map((value) => quoteArgument(value, this.shell)))
    return this
  }

  /** A word inserted as is (an environment variable reference). */
  raw(flag: string, word: string): this {
    this.words.push(flag, word)
    return this
  }

  toString(): string {
    return this.words.join(' ')
  }
}

const MOSQUITTO_VERSIONS: Readonly<Record<MqttProtocolVersion, string>> = {
  3: 'mqttv31',
  4: 'mqttv311',
  5: 'mqttv5'
}
const MQTTX_VERSIONS: Readonly<Record<MqttProtocolVersion, string>> = {
  3: '3.1',
  4: '3.1.1',
  5: '5'
}

/** The client id, only when it is fixed (not empty, not generated by mqtey). */
function fixedClientId(profile: ConnectionProfile): string | null {
  const id = profile.clientId.trim()
  return id === '' || isGeneratedClientId(id) ? null : profile.clientId
}

/** Host, port, version, client id, credentials and TLS, for mosquitto or MQTTX (`mqttx`). */
export function connectionFlags(
  line: CommandLine,
  profile: ConnectionProfile,
  mqttx: boolean
): void {
  line.option('-h', profile.host).option('-p', String(profile.port))
  if (mqttx) {
    if (profile.protocol !== 'mqtt') line.option('-l', profile.protocol)
    if (isWebSocketProtocol(profile.protocol)) line.option('--path', profile.path || '/mqtt')
    line.option('-V', MQTTX_VERSIONS[profile.protocolVersion])
  } else {
    line.option('-V', MOSQUITTO_VERSIONS[profile.protocolVersion])
  }
  const clientId = fixedClientId(profile)
  if (clientId !== null) line.option('-i', clientId)
  if (profile.username !== '') line.option('-u', profile.username)
  if (profile.password !== '') line.raw('-P', passwordArgument(line.shell))
  if (!isTlsProtocol(profile.protocol)) return
  const tls = profile.tls
  if (tls.caPath) line.option(mqttx ? '--ca' : '--cafile', tls.caPath)
  else if (!mqttx) line.flag('--tls-use-os-certs')
  if (tls.certPath) line.option('--cert', tls.certPath)
  if (tls.keyPath) line.option('--key', tls.keyPath)
  if (!tls.rejectUnauthorized) line.flag('--insecure')
  const alpn = tls.alpnProtocols.filter((protocol) => protocol !== '')
  if (alpn.length > 0) {
    if (mqttx) line.option('--alpn', ...alpn)
    else line.option('--tls-alpn', alpn[0])
  }
}
